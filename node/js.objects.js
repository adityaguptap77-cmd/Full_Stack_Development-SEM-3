//key-value pairs are used to store data in JavaScript objects. Each key is a string (or symbol) that is associated with a value, which can be of any data type. Objects are created using curly braces {} and can be manipulated using dot notation or bracket notation.
const user = {
    username : "JohnDoe",
    email : "johndoe@example.com",                  
    age : 30,
    course : "B-tech",
}
console.log(user.username);
console.log(user.email);
console.log(user.age);
console.log(user.course);